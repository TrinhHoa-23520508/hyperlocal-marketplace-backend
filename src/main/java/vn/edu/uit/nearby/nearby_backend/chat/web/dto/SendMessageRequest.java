package vn.edu.uit.nearby.nearby_backend.chat.web.dto;

import java.util.List;
import java.util.UUID;

import org.jspecify.annotations.Nullable;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotNull;

/**
 * One message, sent over REST ({@code POST /conversations/{id}/messages}) or over STOMP
 * ({@code SEND /app/conversations/{id}/messages}); both read the same body (FR-CH-02).
 */
@Schema(description = "A message to send. TEXT needs body; IMAGE needs imageIds (1 to 5 READY images of this "
		+ "conversation); LOCATION needs point. The same clientMsgId is stored once (FR-CH-02)")
public record SendMessageRequest(@Schema(
		description = "Generated by the app for every message; a repeat returns the stored message") @NotNull UUID clientMsgId,
		@NotNull Kind type,
		@Schema(example = "Còn hàng không bạn?", description = "1 to 1 000 characters") @Nullable String body,
		@Nullable List<UUID> imageIds, @Valid @Nullable PointRequest point) {

	public enum Kind {

		TEXT, IMAGE, LOCATION

	}

	@Schema(description = "A meeting point chosen on A13 (FR-CH-05), inside Vietnam")
	public record PointRequest(@Schema(example = "10.7769") double latitude,
			@Schema(example = "106.7009") double longitude,
			@Schema(example = "Công viên 23/9", description = "1 to 100 characters") @Nullable String placeName) {
	}

}
